"""Generate the LaTeX tables of the English report from the analysis CSV files (no database access).

Usage: python -I scripts/generate_latex_tables.py
Inputs : results/analysis/*.csv, config/attendus_v3.2.json
Outputs: reports/latex/generated/*.tex (overwritten on every run)

Rules (identical to the original French report generator; only labels and number format differ):
- percentages are recomputed from ride counts (no double rounding);
- medians, quantiles and means are taken from the CSV files and shown with 2 decimals
  (values computed by PostgreSQL and rounded to 2 decimals at extraction);
- exact decimal rounding (ROUND_HALF_UP), English format (comma thousands separator, decimal point).
"""
import json
import os
from decimal import Decimal, ROUND_HALF_UP

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV = os.path.join(ROOT, "results", "analysis")
OUT = os.path.join(ROOT, "reports", "latex", "generated")
DAYS = {2: "Monday", 3: "Tuesday", 4: "Wednesday", 5: "Thursday", 6: "Friday", 7: "Saturday", 1: "Sunday"}
MONTHS = {"01": "Jan.", "02": "Feb.", "03": "Mar.", "04": "Apr.", "05": "May", "06": "June",
          "07": "July", "08": "Aug.", "09": "Sept.", "10": "Oct.", "11": "Nov.", "12": "Dec."}
DAY_TYPE = {"semaine": "weekday", "week-end": "weekend"}  # values of the type_jour column


def rd(name):
    return pd.read_csv(os.path.join(CSV, f"{name}.csv"))


def num(x, dec=0):
    """Number in English LaTeX format: 6,012,458 ; 11.17."""
    q = Decimal(str(x)).quantize(Decimal(1).scaleb(-dec), rounding=ROUND_HALF_UP)
    return f"{q:,.{dec}f}"


def pct(n, d, dec=1):
    return num(Decimal(int(n)) * 100 / Decimal(int(d)), dec) + "\\%"


def write(name, body):
    with open(os.path.join(OUT, f"{name}.tex"), "w", encoding="utf-8") as f:
        f.write("% Generated by scripts/generate_latex_tables.py - do not edit by hand\n" + body + "\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    exp = json.load(open(os.path.join(ROOT, "config", "attendus_v3.2.json"), encoding="utf-8"))
    u = rd("a01_usagers").set_index("member_casual")
    d2 = rd("a02_durees_tranches")
    tot = {mc: int(u.loc[mc, "trajets"]) for mc in ("member", "casual", "TOUS")}

    # --- Cleaning cascade (config/attendus_v3.2.json) --------------------------------
    ex = exp["excluded"]
    n0 = exp["raw_rows"]
    steps = [("Raw data (12 CSV files)", None, n0)]
    left = n0
    for code, lab in (("duplicate_ride_id", "Duplicate \\texttt{ride\\_id} (copy in the May file)"),
                      ("out_of_period", "Start outside the period (September 2025)"),
                      ("negative_duration", "Negative duration (clock change)"),
                      ("under_60s", "Positive duration shorter than 60~s")):
        left -= ex[code]
        steps.append((lab, ex[code], left))
    assert left == exp["kept"] == tot["TOUS"]
    rows = "\n".join(f"{lab} & {'' if e is None else num(e)} & {num(r)} \\\\" for lab, e, r in steps)
    write("t_cascade", "\\begin{tabularx}{\\linewidth}{Y r r}\n\\toprule\n"
          "\\thead{Step (order of application)} & \\thead{Rows excluded} & \\thead{Rows remaining} \\\\\n\\midrule\n"
          f"{rows}\n\\midrule\n\\textbf{{Total}} & \\textbf{{{num(sum(ex.values()))}}} & \\textbf{{{num(left)}}} \\\\\n\\bottomrule\n\\end{{tabularx}}")

    # --- Summary by rider type --------------------------------------------------------
    def ge(mc, first):  # rides from a duration band onwards (codes 05.., 06..)
        s = d2[(d2.member_casual == mc) & (d2.tranche.str[:2] >= first)].trajets.sum()
        return int(s)
    lines = []
    lines.append(("Rides", num(tot["member"]), num(tot["casual"]), num(tot["TOUS"])))
    lines.append(("Share of rides", pct(tot["member"], tot["TOUS"]), pct(tot["casual"], tot["TOUS"]), "100\\%"))
    for lab, col in (("Median duration (min)", "mediane_min"), ("Mean duration (min)", "moyenne_min"),
                     ("1st quartile / 3rd quartile (min)", None),
                     ("90th percentile (min)", "p90_min")):
        if col is None:
            lines.append((lab, *[f"{num(u.loc[mc, 'p25_min'], 2)} / {num(u.loc[mc, 'p75_min'], 2)}" for mc in ("member", "casual", "TOUS")]))
        else:
            lines.append((lab, *[num(u.loc[mc, col], 2) for mc in ("member", "casual", "TOUS")]))
    lines.append(("Rides of at least 20 min", pct(ge("member", "05"), tot["member"]), pct(ge("casual", "05"), tot["casual"]),
                  pct(ge("member", "05") + ge("casual", "05"), tot["TOUS"])))
    lines.append(("Rides of at least 30 min", pct(ge("member", "06"), tot["member"]), pct(ge("casual", "06"), tot["casual"]),
                  pct(ge("member", "06") + ge("casual", "06"), tot["TOUS"])))
    lines.append(("Rides longer than 24 hours", num(u.loc["member", "trajets_plus_24h"]), num(u.loc["casual", "trajets_plus_24h"]),
                  num(u.loc["TOUS", "trajets_plus_24h"])))
    body = "\n".join(" & ".join(l) + " \\\\" for l in lines)
    write("t_usagers", "\\begin{tabularx}{\\linewidth}{Y r r r}\n\\toprule\n"
          "\\thead{Indicator} & \\thead{\\textcolor{member}{Members}} & \\thead{\\textcolor{casual}{Casual riders}} & \\thead{All} \\\\\n\\midrule\n"
          f"{body}\n\\bottomrule\n\\end{{tabularx}}")

    # --- Day of the week -------------------------------------------------------------
    j = rd("a03_jour")
    rows = []
    for k in (2, 3, 4, 5, 6, 7, 1):
        r = {mc: j[(j.member_casual == mc) & (j.day_of_week == k)].iloc[0] for mc in ("member", "casual")}
        rows.append(f"{DAYS[k]} & {pct(r['member'].trajets, tot['member'])} & {pct(r['casual'].trajets, tot['casual'])} & "
                    f"{num(r['member'].mediane_min, 2)} & {num(r['casual'].mediane_min, 2)} \\\\")
    we = {mc: int(j[(j.member_casual == mc) & (j.day_of_week.isin([1, 7]))].trajets.sum()) for mc in ("member", "casual")}
    write("t_jours", "\\begin{tabularx}{\\linewidth}{Y r r r r}\n\\toprule\n"
          " & \\multicolumn{2}{c}{\\thead{Share of the group's rides}} & \\multicolumn{2}{c}{\\thead{Median duration (min)}} \\\\\n"
          "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n\\thead{Day of departure} & \\thead{Members} & \\thead{Casual} & \\thead{Members} & \\thead{Casual} \\\\\n\\midrule\n"
          + "\n".join(rows) + "\n\\midrule\n"
          f"\\textbf{{Weekend (Sat.\\,+\\,Sun.)}} & \\textbf{{{pct(we['member'], tot['member'])}}} & \\textbf{{{pct(we['casual'], tot['casual'])}}} & & \\\\\n"
          "\\bottomrule\n\\end{tabularx}")

    # --- Months ------------------------------------------------------------------------
    m = rd("a04_mois")
    rows = []
    for mo in sorted(m.mois.unique()):
        r = {mc: m[(m.mois == mo) & (m.member_casual == mc)].iloc[0] for mc in ("member", "casual")}
        n = int(r["member"].trajets) + int(r["casual"].trajets)
        rows.append(f"{MONTHS[mo[5:]]} {mo[:4]} & {num(r['member'].trajets)} & {num(r['casual'].trajets)} & "
                    f"{pct(r['casual'].trajets, n)} & {num(r['member'].mediane_min, 2)} & {num(r['casual'].mediane_min, 2)} \\\\")
    write("t_mois", "\\begin{tabularx}{\\linewidth}{L{1.9cm} R R R R R}\n\\toprule\n"
          "\\thead{Month of departure} & \\thead{Member rides} & \\thead{Casual rides} & \\thead{Casual share} & "
          "\\thead{Median, members (min)} & \\thead{Median, casual (min)} \\\\\n\\midrule\n"
          + "\n".join(rows) + f"\n\\midrule\n\\textbf{{Total}} & \\textbf{{{num(tot['member'])}}} & \\textbf{{{num(tot['casual'])}}} & "
          f"\\textbf{{{pct(tot['casual'], tot['TOUS'])}}} & & \\\\\n\\bottomrule\n\\end{{tabularx}}")

    # --- Bike type x type of day --------------------------------------------------------
    it = rd("a07_interactions")
    lab = {"classic_bike": "Classic", "electric_bike": "Electric"}
    rows = []
    for rt in ("classic_bike", "electric_bike"):
        for tj in ("semaine", "week-end"):
            r = {mc: it[(it.member_casual == mc) & (it.rideable_type == rt) & (it.type_jour == tj)].iloc[0] for mc in ("member", "casual")}
            rows.append(f"{lab[rt]}, {DAY_TYPE[tj]} & {pct(r['member'].trajets, tot['member'])} & {pct(r['casual'].trajets, tot['casual'])} & "
                        f"{num(r['member'].mediane_min, 2)} & {num(r['casual'].mediane_min, 2)} \\\\")
    v = rd("a06_velo")
    eb = {mc: int(v[(v.member_casual == mc) & (v.rideable_type == "electric_bike")].trajets.iloc[0]) for mc in ("member", "casual")}
    write("t_velo_jour", "\\begin{tabularx}{\\linewidth}{Y r r r r}\n\\toprule\n"
          " & \\multicolumn{2}{c}{\\thead{Share of the group's rides}} & \\multicolumn{2}{c}{\\thead{Median duration (min)}} \\\\\n"
          "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\n\\thead{Bike, type of day} & \\thead{Members} & \\thead{Casual} & \\thead{Members} & \\thead{Casual} \\\\\n\\midrule\n"
          + "\n".join(rows) + "\n\\midrule\n"
          f"\\textbf{{E-bike (total)}} & \\textbf{{{pct(eb['member'], tot['member'])}}} & \\textbf{{{pct(eb['casual'], tot['casual'])}}} & & \\\\\n"
          "\\bottomrule\n\\end{tabularx}")

    # --- Hours: derived indicators -------------------------------------------------------
    h = rd("a05_heure")
    def share(mc, tj, hours, denom="type"):
        sub = h[(h.member_casual == mc) & (h.type_jour == tj)]
        n = int(sub[sub.heure.isin(hours)].trajets.sum())
        d = int(sub.trajets.sum()) if denom == "type" else tot[mc]
        return pct(n, d)
    rows = [
        ("Departures 7--9 a.m., \\% of weekday rides", share("member", "semaine", [7, 8]), share("casual", "semaine", [7, 8])),
        ("Departures 5--6 p.m., \\% of weekday rides", share("member", "semaine", [17]), share("casual", "semaine", [17])),
        ("Departures 10 a.m.--4 p.m., \\% of weekday rides", share("member", "semaine", list(range(10, 16))), share("casual", "semaine", list(range(10, 16)))),
        ("Departures 10 a.m.--4 p.m., \\% of weekend rides", share("member", "week-end", list(range(10, 16))), share("casual", "week-end", list(range(10, 16)))),
        ("Weekday peak hours (7--9 a.m. and 4--7 p.m.), \\% of all the group's rides",
         share("member", "semaine", [7, 8, 16, 17, 18], "all"), share("casual", "semaine", [7, 8, 16, 17, 18], "all")),
    ]
    write("t_heures", "\\begin{tabularx}{\\linewidth}{Y r r}\n\\toprule\n\\thead{Hourly indicator (local time of departure)} & "
          "\\thead{Members} & \\thead{Casual} \\\\\n\\midrule\n" + "\n".join(" & ".join(r) + " \\\\" for r in rows)
          + "\n\\bottomrule\n\\end{tabularx}")

    # --- Round trips -----------------------------------------------------------------------
    b = rd("a08_boucles").set_index("member_casual")
    rows = []
    for mc, lb in (("member", "Members"), ("casual", "Casual riders")):
        rows.append(f"{lb} & {num(b.loc[mc, 'trajets_avec_2_stations'])} ({pct(b.loc[mc, 'trajets_avec_2_stations'], b.loc[mc, 'trajets'], 0)}) & "
                    f"{num(b.loc[mc, 'trajets_boucle'])} & {pct(b.loc[mc, 'trajets_boucle'], b.loc[mc, 'trajets_avec_2_stations'])} & "
                    f"{num(b.loc[mc, 'mediane_boucle_min'], 2)} \\\\")
    write("t_boucles", "\\begin{tabularx}{\\linewidth}{Y R R R R}\n\\toprule\n\\thead{Group} & \\thead{Rides with both stations} & "
          "\\thead{Round trips} & \\thead{Share of round trips} & \\thead{Median round trip (min)} \\\\\n\\midrule\n"
          + "\n".join(rows) + "\n\\bottomrule\n\\end{tabularx}")
    print(f"Tables written to {OUT}")


if __name__ == "__main__":
    main()
